export type IconName = keyof typeof icons;

type Props = { name: IconName; size?: number; tone?: Tone; color?: string; strokeWidth?: number };

export function Icon({ name, size = 20, tone = "texte", color, strokeWidth = 1.8 }: Props) {
  const { colors } = useTheme();
  const Component = icons[name];
  return <Component size={size} color={color ?? colors[tone]} strokeWidth={strokeWidth} />;
}
